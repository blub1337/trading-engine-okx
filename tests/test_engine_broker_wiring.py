"""Phase 10.2.1.2 — Broker wiring regression tests.

These tests verify that a default TradingEngine properly wires its PaperBroker
to the same SQLiteStore used by the engine, and that a normal broker
place() call persists a durable PaperOrder usable for crash recovery.
"""

import os
import tempfile
from datetime import datetime, timezone
from unittest.mock import MagicMock

from trading_engine.engine import TradingEngine
from trading_engine.marketdata import TickerSnapshot
from trading_engine.models import Signal, SignalSide


# ---------------------------------------------------------------------------
# Test E: Default PaperBroker wiring via normal engine
# ---------------------------------------------------------------------------

def test_default_broker_persists_paper_order_through_normal_engine():
    """Test that a normal TradingEngine construction persists paper orders via PaperBroker.

    Requirement from Phase 10.2.1.2:
    - Create a temporary file-backed SQLite database.
    - Create a real TradingEngine (normal constructor).
    - Do NOT replace engine.broker.
    - Use a deterministic fake market-data provider.
    - Process a valid signal with a stable signal_id.
    - Verify that the default PaperBroker places and persists the FILLED PaperOrder.
    - Verify correct client_order_id and broker_order_id.
    - Verify execution and portfolio state are persisted.
    """
    db_path = os.path.join(tempfile.mkdtemp(), "test_default_broker.db")

    # Providers
    mock_provider = MagicMock()
    snapshot = TickerSnapshot(
        inst_id="BTC-USDT",
        last=50000.0,
        bid=None,
        ask=None,
        open_24h=None,
        high_24h=None,
        low_24h=None,
        ts=datetime.now(timezone.utc),
        received_at=datetime.now(timezone.utc),
    )
    mock_provider.get_ticker.return_value = snapshot
    mock_provider.close = MagicMock()

    engine = TradingEngine(
        db_path=db_path,
        market_data_provider=mock_provider,
    )

    # Verify automatic wiring: broker uses the engine's store
    assert engine.broker._store is engine.store

    store = engine.store

    try:
        store.update_cash(100000.0)
        cash_before = store.get_portfolio()["cash"]

        signal = Signal(
            strategy="test",
            asset="BTC-USDT",
            side=SignalSide.LONG,
            conf=0.8,
            rationale="default broker persistence test",
            required_inputs=["close"],
            issued_at=datetime.now(timezone.utc),
            signal_id="default-broker-test-001",
        )

        result = engine.process_signal(signal)

        # Verify execution succeeded
        assert result.status == "FILLED", f"Expected FILLED, got {result.status}"
        assert result.filled is True
        assert result.order_id is not None, "Execution must have an order_id"

        # client_order_id is generated by _create_intent() as UUID, not signal_id
        # signal_id linkage is stored in order_intents.signal_ref_id
        intent_row = store.get_order_intent_by_signal_ref("default-broker-test-001")
        assert intent_row is not None, "Order intent must exist with signal_ref_id"
        assert intent_row["client_order_id"] == result.client_order_id

        # Verify PaperBroker persisted the PaperOrder
        client_order_id = intent_row["client_order_id"]
        paper_order = store.get_paper_order(client_order_id)
        assert paper_order is not None, "Paper order must be persisted"
        assert paper_order["status"] == "FILLED"
        assert paper_order["broker_order_id"] == result.order_id
        assert paper_order["fill_price"] == result.fill_price
        assert paper_order["fill_qty"] == result.fill_qty
        assert paper_order["fee"] == result.fee

        # Verify execution record exists
        exec_row = store.get_execution(signal.signal_id)
        if exec_row is None:
            # Fallback: find by client_order_id via signal ref
            intent_row = store.get_order_intent_by_signal_ref("default-broker-test-001")
            assert intent_row is not None
            intent_id = intent_row["id"]
            exec_row = store.get_execution(intent_id)
        assert exec_row is not None
        assert exec_row["status"] == "FILLED"

        # Verify portfolio was updated
        portfolio = store.get_portfolio()
        assert portfolio["cash"] < cash_before, (
            f"Portfolio cash must decrease after fill: {cash_before} -> {portfolio['cash']}"
        )

    finally:
        store.close()


